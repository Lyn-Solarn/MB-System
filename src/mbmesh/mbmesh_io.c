int mbmesh_write_mesh(struct mbmesh_mesh *mesh, struct mbmesh_control *control) {
    /* Write mesh in specified output format */
    int status = MB_SUCCESS;
    
    switch (control->output_format) {
    case MBMESH_FORMAT_GMT:
        status = mbmesh_write_gmt(mesh, control);
        break;
    case MBMESH_FORMAT_VTK:
        status = mbmesh_write_vtk(mesh, control);
        break;
    case MBMESH_FORMAT_OBJ:
        status = mbmesh_write_obj(mesh, control);  /* Need to implement */
        break;
    case MBMESH_FORMAT_STL:
        status = mbmesh_write_stl(mesh, control);  /* Need to implement */
        break;
    case MBMESH_FORMAT_JSON:
        status = mbmesh_write_json(mesh, control);  /* Add for web viewing */
        break;
    default:
        fprintf(stderr, "Unknown output format: %d\n", control->output_format);
        status = MB_FAILURE;
        break;
    }
    
    return status;
}

